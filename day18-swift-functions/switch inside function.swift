
//switch inside functions

func calcDay(day:Int){
    switch day{
    case 1:
        print("Monday")
    case 2:
        print("Tuesday")
    case 3:
        print("Wenesday")
    case 4:
        print("Thursday")
    case 5:
        print("Friday")
    case 6:
        print("Saturday")
    case 7:
        print("Sunday")
    default:
        print("Invalid")
    }
}
calcDay(day: 1)
calcDay(day: 5)


